export function searchAirportsQuery(query: string) {
  if (!query) return topAirports.slice(0, 5);
  const q = query.toLowerCase();
  return topAirports.filter(
    a => a.code.toLowerCase().includes(q) || a.name.toLowerCase().includes(q) || a.location.toLowerCase().includes(q)
  ).slice(0, 6);
}
